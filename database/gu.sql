-- Table: Password history
-- Each password row belongs to one utilisateur and preserves the complete password history.
CREATE TABLE IF NOT EXISTS gu.password_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES gu.utilisateurs(id),
    "password" VARCHAR(255) NOT NULL,
    "current" BOOLEAN NOT NULL DEFAULT TRUE,
    date_insertion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_changement TIMESTAMPTZ,
    CONSTRAINT chk_password_history_current_dates CHECK (
        ("current" AND date_changement IS NULL)
        OR (NOT "current" AND date_changement IS NOT NULL)
    )
);

-- A user may have one current password only; prior password rows remain as history.
CREATE UNIQUE INDEX IF NOT EXISTS uq_password_history_current_utilisateur
    ON gu.password_history (utilisateur_id)
    WHERE "current";

CREATE INDEX IF NOT EXISTS idx_password_history_utilisateur_date
    ON gu.password_history (utilisateur_id, date_insertion DESC);

-- Inserting or reactivating a current password archives the prior current password for that user.
-- Password values and their utilisateur association are immutable: insert a new row instead of overwriting history.
CREATE OR REPLACE FUNCTION gu.manage_password_history()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW."password" IS DISTINCT FROM OLD."password" THEN
            RAISE EXCEPTION 'Password history is immutable. Insert a new password_history row instead.';
        END IF;

        IF NEW.utilisateur_id IS DISTINCT FROM OLD.utilisateur_id THEN
            RAISE EXCEPTION 'A password history row cannot be moved to another utilisateur.';
        END IF;

        IF NOT OLD."current" AND NEW."current" THEN
            UPDATE gu.password_history
            SET "current" = FALSE,
                date_changement = CURRENT_TIMESTAMP
            WHERE "current"
              AND id <> NEW.id
              AND utilisateur_id = NEW.utilisateur_id;

            NEW.date_changement := NULL;
        ELSIF OLD."current" AND NOT NEW."current" THEN
            NEW.date_changement := COALESCE(NEW.date_changement, CURRENT_TIMESTAMP);
        END IF;
    ELSIF TG_OP = 'INSERT' AND NEW."current" THEN
        UPDATE gu.password_history
        SET "current" = FALSE,
            date_changement = CURRENT_TIMESTAMP
        WHERE "current"
          AND utilisateur_id = NEW.utilisateur_id;

        NEW.date_changement := NULL;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_password_history_manage_current ON gu.password_history;

CREATE TRIGGER trg_password_history_manage_current
BEFORE INSERT OR UPDATE OF "password", "current", utilisateur_id ON gu.password_history
FOR EACH ROW
EXECUTE FUNCTION gu.manage_password_history();

COMMIT;
