-- Schema: gu
-- ConnectMarket application database namespace.
-- This script is tracked for manual execution; it is not run automatically by Spring Boot.

BEGIN;

CREATE SCHEMA IF NOT EXISTS gu AUTHORIZATION sorelle;

-- Table: Client
CREATE TABLE IF NOT EXISTS gu.client (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    login VARCHAR(100) NOT NULL,
    statut VARCHAR(30) NOT NULL DEFAULT 'ACTIF',
    "dateCreation" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_client_email UNIQUE (email),
    CONSTRAINT uq_client_login UNIQUE (login)
);

-- Table: Administrateur
CREATE TABLE IF NOT EXISTS gu.administrateur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    login VARCHAR(100) NOT NULL,
    statut VARCHAR(30) NOT NULL DEFAULT 'ACTIF',
    "dateCreation" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_administrateur_email UNIQUE (email),
    CONSTRAINT uq_administrateur_login UNIQUE (login)
);

-- Table: Vendeur
CREATE TABLE IF NOT EXISTS gu.vendeur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    login VARCHAR(100) NOT NULL,
    statut VARCHAR(30) NOT NULL DEFAULT 'ACTIF',
    "dateCreation" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_vendeur_email UNIQUE (email),
    CONSTRAINT uq_vendeur_login UNIQUE (login)
);

-- Table: BASIC_RIGHTS
CREATE TABLE IF NOT EXISTS gu.basic_rights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL,
    br_name VARCHAR(150) NOT NULL,
    CONSTRAINT uq_basic_rights_code UNIQUE (code)
);

-- Table: Password history
-- Exactly one of client_id, administrateur_id, or vendeur_id is set for every row.
CREATE TABLE IF NOT EXISTS gu.password_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT REFERENCES gu.client(id),
    administrateur_id BIGINT REFERENCES gu.administrateur(id),
    vendeur_id BIGINT REFERENCES gu.vendeur(id),
    "password" VARCHAR(255) NOT NULL,
    "current" BOOLEAN NOT NULL DEFAULT TRUE,
    date_insertion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_changement TIMESTAMPTZ,
    CONSTRAINT chk_password_history_one_account CHECK (
        num_nonnulls(client_id, administrateur_id, vendeur_id) = 1
    ),
    CONSTRAINT chk_password_history_current_dates CHECK (
        ("current" AND date_changement IS NULL)
        OR (NOT "current" AND date_changement IS NOT NULL)
    )
);

-- A login may have one current password only; previous password rows remain as history.
CREATE UNIQUE INDEX IF NOT EXISTS uq_password_history_current_client
    ON gu.password_history (client_id)
    WHERE "current" AND client_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_password_history_current_administrateur
    ON gu.password_history (administrateur_id)
    WHERE "current" AND administrateur_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_password_history_current_vendeur
    ON gu.password_history (vendeur_id)
    WHERE "current" AND vendeur_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_password_history_client_date
    ON gu.password_history (client_id, date_insertion DESC)
    WHERE client_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_password_history_administrateur_date
    ON gu.password_history (administrateur_id, date_insertion DESC)
    WHERE administrateur_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_password_history_vendeur_date
    ON gu.password_history (vendeur_id, date_insertion DESC)
    WHERE vendeur_id IS NOT NULL;

-- Inserting a new current password archives the prior current password for that account.
-- Password values are immutable: insert a new row instead of overwriting an old password.
CREATE OR REPLACE FUNCTION gu.manage_password_history()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW."password" IS DISTINCT FROM OLD."password" THEN
            RAISE EXCEPTION 'Password history is immutable. Insert a new password_history row instead.';
        END IF;

        IF NOT OLD."current" AND NEW."current" THEN
            UPDATE gu.password_history
            SET "current" = FALSE,
                date_changement = CURRENT_TIMESTAMP
            WHERE "current"
              AND id <> NEW.id
              AND (
                  (NEW.client_id IS NOT NULL AND client_id = NEW.client_id)
                  OR (NEW.administrateur_id IS NOT NULL AND administrateur_id = NEW.administrateur_id)
                  OR (NEW.vendeur_id IS NOT NULL AND vendeur_id = NEW.vendeur_id)
              );

            NEW.date_changement := NULL;
        ELSIF OLD."current" AND NOT NEW."current" THEN
            NEW.date_changement := COALESCE(NEW.date_changement, CURRENT_TIMESTAMP);
        END IF;
    ELSIF TG_OP = 'INSERT' AND NEW."current" THEN
        UPDATE gu.password_history
        SET "current" = FALSE,
            date_changement = CURRENT_TIMESTAMP
        WHERE "current"
          AND (
              (NEW.client_id IS NOT NULL AND client_id = NEW.client_id)
              OR (NEW.administrateur_id IS NOT NULL AND administrateur_id = NEW.administrateur_id)
              OR (NEW.vendeur_id IS NOT NULL AND vendeur_id = NEW.vendeur_id)
          );

        NEW.date_changement := NULL;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_password_history_manage_current ON gu.password_history;

CREATE TRIGGER trg_password_history_manage_current
BEFORE INSERT OR UPDATE OF "password", "current" ON gu.password_history
FOR EACH ROW
EXECUTE FUNCTION gu.manage_password_history();

COMMIT;
