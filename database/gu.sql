-- Schema: gu
-- CacaoMARKETCM application database namespace.
-- This script is tracked for manual execution; it is not run automatically by Spring Boot.

BEGIN;

CREATE SCHEMA IF NOT EXISTS gu AUTHORIZATION sorelle;

-- Table: Type utilisateur
-- The lookup values determine whether an utilisateur is a client, vendeur, or administrateur.
CREATE TABLE IF NOT EXISTS gu.type_utilisateur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    tu_name VARCHAR(100) NOT NULL,
    CONSTRAINT uq_type_utilisateur_code UNIQUE (code),
    CONSTRAINT uq_type_utilisateur_name UNIQUE (tu_name)
);

INSERT INTO gu.type_utilisateur (code, tu_name)
VALUES
    ('CLIENT', 'Client'),
    ('VENDEUR', 'Vendeur'),
    ('ADMINISTRATEUR', 'Administrateur')
ON CONFLICT (code) DO UPDATE
SET tu_name = EXCLUDED.tu_name;

-- Table: Utilisateurs
CREATE TABLE IF NOT EXISTS gu.utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_utilisateur_id BIGINT NOT NULL REFERENCES gu.type_utilisateur(id),
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    login VARCHAR(100) NOT NULL,
    statut VARCHAR(30) NOT NULL DEFAULT 'ACTIF',
    "dateCreation" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_utilisateurs_email UNIQUE (email),
    CONSTRAINT uq_utilisateurs_login UNIQUE (login)
);

CREATE INDEX IF NOT EXISTS idx_utilisateurs_type_utilisateur
    ON gu.utilisateurs (type_utilisateur_id);

-- Registration and login compare identities without regard to case.
CREATE UNIQUE INDEX IF NOT EXISTS uq_utilisateurs_email_lower
    ON gu.utilisateurs (LOWER(email));

CREATE UNIQUE INDEX IF NOT EXISTS uq_utilisateurs_login_lower
    ON gu.utilisateurs (LOWER(login));

-- Table: Connected browser sessions
-- One row is created after each successful login. The raw servlet/JSESSIONID value is never
-- stored; session_hash is a SHA-256 hash so several browser sessions can be managed safely.
CREATE TABLE IF NOT EXISTS gu.sessions_utilisateur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES gu.utilisateurs(id) ON DELETE CASCADE,
    session_hash CHAR(64) NOT NULL,
    browser_label VARCHAR(120) NOT NULL,
    remember_me BOOLEAN NOT NULL DEFAULT FALSE,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    invalidated_at TIMESTAMPTZ,
    CONSTRAINT uq_sessions_utilisateur_session_hash UNIQUE (session_hash),
    CONSTRAINT chk_sessions_utilisateur_dates CHECK (
        last_seen_at >= date_creation
        AND expires_at >= last_seen_at
        AND (invalidated_at IS NULL OR invalidated_at >= date_creation)
    )
);

CREATE INDEX IF NOT EXISTS idx_sessions_utilisateur_utilisateur_active
    ON gu.sessions_utilisateur (utilisateur_id, last_seen_at DESC)
    WHERE invalidated_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_sessions_utilisateur_expiration_active
    ON gu.sessions_utilisateur (expires_at)
    WHERE invalidated_at IS NULL;

-- Table: Registration confirmations
-- A pending utilisateur receives one hashed, single-use email-confirmation token.
-- Raw tokens are deliberately never stored in PostgreSQL.
CREATE TABLE IF NOT EXISTS gu.registration_confirmation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES gu.utilisateurs(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_registration_confirmation_utilisateur UNIQUE (utilisateur_id),
    CONSTRAINT uq_registration_confirmation_token_hash UNIQUE (token_hash),
    CONSTRAINT chk_registration_confirmation_dates CHECK (
        confirmed_at IS NULL OR confirmed_at <= expires_at
    )
);

CREATE INDEX IF NOT EXISTS idx_registration_confirmation_expiration
    ON gu.registration_confirmation (expires_at)
    WHERE confirmed_at IS NULL;

-- Table: Password-reset requests
-- Only active (therefore confirmed) utilisateurs receive a reset link. The raw link token is
-- never stored; only its SHA-256 hash is persisted. A new request replaces a prior unused token.
CREATE TABLE IF NOT EXISTS gu.password_reset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES gu.utilisateurs(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_password_reset_utilisateur UNIQUE (utilisateur_id),
    CONSTRAINT uq_password_reset_token_hash UNIQUE (token_hash),
    CONSTRAINT chk_password_reset_dates CHECK (
        used_at IS NULL OR used_at <= expires_at
    )
);

CREATE INDEX IF NOT EXISTS idx_password_reset_expiration
    ON gu.password_reset (expires_at)
    WHERE used_at IS NULL;

-- Table: BASIC_RIGHTS
CREATE TABLE IF NOT EXISTS gu.basic_rights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL,
    br_name VARCHAR(150) NOT NULL,
    CONSTRAINT uq_basic_rights_code UNIQUE (code)
);

-- Table: Associations between user types and basic rights
CREATE TABLE IF NOT EXISTS gu.type_utilisateur_basic_right (
    type_utilisateur_id BIGINT NOT NULL REFERENCES gu.type_utilisateur(id),
    basic_right_id BIGINT NOT NULL REFERENCES gu.basic_rights(id),
    "dateCreation" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (type_utilisateur_id, basic_right_id)
);

-- An ADMINISTRATEUR type receives every existing basic right.
CREATE OR REPLACE FUNCTION gu.assign_all_basic_rights_to_administrateur()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.code = 'ADMINISTRATEUR' THEN
        INSERT INTO gu.type_utilisateur_basic_right (type_utilisateur_id, basic_right_id)
        SELECT NEW.id, br.id
        FROM gu.basic_rights AS br
        ON CONFLICT DO NOTHING;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_type_utilisateur_assign_administrateur_rights ON gu.type_utilisateur;

CREATE TRIGGER trg_type_utilisateur_assign_administrateur_rights
AFTER INSERT OR UPDATE OF code ON gu.type_utilisateur
FOR EACH ROW
EXECUTE FUNCTION gu.assign_all_basic_rights_to_administrateur();

-- Every newly-created basic right is automatically assigned to ADMINISTRATEUR.
CREATE OR REPLACE FUNCTION gu.assign_basic_right_to_administrateur()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO gu.type_utilisateur_basic_right (type_utilisateur_id, basic_right_id)
    SELECT tu.id, NEW.id
    FROM gu.type_utilisateur AS tu
    WHERE tu.code = 'ADMINISTRATEUR'
    ON CONFLICT DO NOTHING;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_basic_right_assign_administrateur ON gu.basic_rights;

CREATE TRIGGER trg_basic_right_assign_administrateur
AFTER INSERT ON gu.basic_rights
FOR EACH ROW
EXECUTE FUNCTION gu.assign_basic_right_to_administrateur();

-- Basic rights cannot be removed or reassigned from the ADMINISTRATEUR type.
CREATE OR REPLACE FUNCTION gu.prevent_administrateur_basic_right_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM gu.type_utilisateur AS tu
        WHERE tu.id = OLD.type_utilisateur_id
          AND tu.code = 'ADMINISTRATEUR'
    ) THEN
        RAISE EXCEPTION 'Basic rights cannot be removed or reassigned from the ADMINISTRATEUR type.';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_type_utilisateur_basic_right_protect_administrateur ON gu.type_utilisateur_basic_right;

CREATE TRIGGER trg_type_utilisateur_basic_right_protect_administrateur
BEFORE DELETE OR UPDATE ON gu.type_utilisateur_basic_right
FOR EACH ROW
EXECUTE FUNCTION gu.prevent_administrateur_basic_right_change();

-- The first basic right: every user type can connect to the application.
INSERT INTO gu.basic_rights (code, br_name)
VALUES ('APP-CONN', 'Connexion a l''application CacaoMARKETCM')
ON CONFLICT (code) DO UPDATE
SET br_name = EXCLUDED.br_name;

INSERT INTO gu.type_utilisateur_basic_right (type_utilisateur_id, basic_right_id)
SELECT tu.id, br.id
FROM gu.type_utilisateur AS tu
CROSS JOIN gu.basic_rights AS br
WHERE br.code = 'APP-CONN'
ON CONFLICT DO NOTHING;

-- Ensure ADMINISTRATEUR is associated with every existing basic right.
INSERT INTO gu.type_utilisateur_basic_right (type_utilisateur_id, basic_right_id)
SELECT tu.id, br.id
FROM gu.type_utilisateur AS tu
CROSS JOIN gu.basic_rights AS br
WHERE tu.code = 'ADMINISTRATEUR'
ON CONFLICT DO NOTHING;

-- Table: Password history
-- Each password row belongs to one utilisateur and preserves the complete password history.
CREATE TABLE IF NOT EXISTS gu.password_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES gu.utilisateurs(id),
    "password" VARCHAR(255) NOT NULL,
    "current" BOOLEAN NOT NULL DEFAULT TRUE,
    date_insertion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_changement TIMESTAMPTZ,
    CONSTRAINT chk_password_history_current_dates CHECK (
        ("current" AND date_changement IS NULL)
        OR (NOT "current" AND date_changement IS NOT NULL)
    )
);

-- A user may have one current password only; prior password rows remain as history.
CREATE UNIQUE INDEX IF NOT EXISTS uq_password_history_current_utilisateur
    ON gu.password_history (utilisateur_id)
    WHERE "current";

CREATE INDEX IF NOT EXISTS idx_password_history_utilisateur_date
    ON gu.password_history (utilisateur_id, date_insertion DESC);

-- Inserting or reactivating a current password archives the prior current password for that user.
-- Password values and their utilisateur association are immutable: insert a new row instead of overwriting history.
CREATE OR REPLACE FUNCTION gu.manage_password_history()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW."password" IS DISTINCT FROM OLD."password" THEN
            RAISE EXCEPTION 'Password history is immutable. Insert a new password_history row instead.';
        END IF;

        IF NEW.utilisateur_id IS DISTINCT FROM OLD.utilisateur_id THEN
            RAISE EXCEPTION 'A password history row cannot be moved to another utilisateur.';
        END IF;

        IF NOT OLD."current" AND NEW."current" THEN
            UPDATE gu.password_history
            SET "current" = FALSE,
                date_changement = CURRENT_TIMESTAMP
            WHERE "current"
              AND id <> NEW.id
              AND utilisateur_id = NEW.utilisateur_id;

            NEW.date_changement := NULL;
        ELSIF OLD."current" AND NOT NEW."current" THEN
            NEW.date_changement := COALESCE(NEW.date_changement, CURRENT_TIMESTAMP);
        END IF;
    ELSIF TG_OP = 'INSERT' AND NEW."current" THEN
        UPDATE gu.password_history
        SET "current" = FALSE,
            date_changement = CURRENT_TIMESTAMP
        WHERE "current"
          AND utilisateur_id = NEW.utilisateur_id;

        NEW.date_changement := NULL;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_password_history_manage_current ON gu.password_history;

CREATE TRIGGER trg_password_history_manage_current
BEFORE INSERT OR UPDATE OF "password", "current", utilisateur_id ON gu.password_history
FOR EACH ROW
EXECUTE FUNCTION gu.manage_password_history();

